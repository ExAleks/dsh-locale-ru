// Build the Russian language pack's browser artifact.
//
// Inputs:
//   localesFile        ref/locales.json          shipped en/zh namespace dictionaries
//   translationsFile   translations/ru.json      namespace -> key -> Russian
//   packageTextFile    translations/package-text.ru.json   English manifest text -> Russian
//   serverTextFile     translations/server-messages.ru.json  templates for server-authored copy
//   manifestTextsFile  ref/manifest-texts.json   every display string packages expose
//   outFile, packageName
import fs from 'node:fs'

const [, , localesFile, translationsFile, packageTextFile, serverTextFile, manifestTextsFile, outFile, packageName] = process.argv

const locales = JSON.parse(fs.readFileSync(localesFile, 'utf8')).namespaces
const translations = JSON.parse(fs.readFileSync(translationsFile, 'utf8'))
const packageText = JSON.parse(fs.readFileSync(packageTextFile, 'utf8'))
const serverText = JSON.parse(fs.readFileSync(serverTextFile, 'utf8'))
const manifestTexts = JSON.parse(fs.readFileSync(manifestTextsFile, 'utf8'))

const placeholders = (text) => {
  const found = new Set()
  for (const m of String(text).matchAll(/\{(\w+)\}/g)) found.add(m[1])
  return [...found].sort().join(',')
}

const problems = []
let keyCount = 0
const namespaces = Object.keys(translations).sort()

for (const ns of namespaces) {
  const source = locales[ns]?.en?.entries
  if (!source) {
    problems.push(`namespace "${ns}" does not exist in the shipped dictionaries`)
    continue
  }
  for (const [key, value] of Object.entries(translations[ns])) {
    if (!(key in source)) {
      problems.push(`${ns}.${key}: key is not in the shipped English dictionary`)
      continue
    }
    if (typeof value !== 'string') {
      problems.push(`${ns}.${key}: translation is not a string`)
      continue
    }
    const expected = placeholders(source[key])
    const actual = placeholders(value)
    if (expected !== actual) {
      problems.push(`${ns}.${key}: placeholders differ (en: ${expected || 'none'} | ru: ${actual || 'none'})`)
      continue
    }
    keyCount++
  }
}

// Package display text: every override must name real manifest text.
const knownText = new Set()
for (const row of manifestTexts) {
  if (typeof row.title === 'string') knownText.add(row.title)
  if (typeof row.description === 'string') knownText.add(row.description)
}
let packageTextCount = 0
for (const [source, value] of Object.entries(packageText)) {
  if (source.trim() === '' || typeof value !== 'string' || value.trim() === '') {
    problems.push(`package text: empty key or value for "${source.slice(0, 40)}"`)
    continue
  }
  if (!knownText.has(source)) {
    problems.push(`package text: "${source.slice(0, 60)}" is not display text of any installed package`)
    continue
  }
  packageTextCount++
}

let serverTextCount = 0
for (const [name, template] of Object.entries(serverText)) {
  if (typeof template !== 'string' || template.trim() === '') {
    problems.push(`server text "${name}" is empty`)
    continue
  }
  const used = new Set([...template.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))
  for (const required of ['amount', 'currency', 'date']) {
    if (!used.has(required)) problems.push(`server text "${name}" does not use {${required}}`)
  }
  serverTextCount++
}

const coverage = {
  titles: manifestTexts.filter((row) => typeof row.title === 'string').length,
  descriptions: manifestTexts.filter((row) => typeof row.description === 'string').length,
}
const uncoveredDescriptions = manifestTexts
  .map((row) => row.description)
  .filter((text) => typeof text === 'string' && !(text in packageText) && !/^@?[\w./-]+$/.test(text))

if (problems.length) {
  console.error(`build check failed (${problems.length}):`)
  for (const p of problems) console.error(`  ${p}`)
  process.exit(1)
}

const ordered = Object.fromEntries(namespaces.map((ns) => [ns, translations[ns]]))
const orderedPackageText = Object.fromEntries(Object.entries(packageText).sort((a, b) => a[0].localeCompare(b[0])))
const orderedServerText = Object.fromEntries(Object.entries(serverText).sort((a, b) => a[0].localeCompare(b[0])))

const banner = `// ${packageName} — Russian language pack for the Harness web UI.
// Generated by tools/build-locale-ru.mjs; do not edit by hand.
// ${keyCount} dictionary keys across ${namespaces.length} namespaces,
// ${packageTextCount} package display strings resolved from manifests,
// ${serverTextCount} template(s) for server-authored copy.`

const body = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(packageName)},
  factory() {
    const dictionaries = ${JSON.stringify(ordered, null, 2)};
    const packageText = ${JSON.stringify(orderedPackageText, null, 2)};
    const serverText = ${JSON.stringify(orderedServerText, null, 2)};

    /**
     * Plugin and bundle titles/descriptions come from each package's own manifest,
     * which ships English and Chinese only, and the locale service's package-text
     * resolver deliberately ignores namespace dictionaries. While this pack is
     * loaded, resolve known English manifest text to Russian and pass everything
     * else through untouched; a package that ships its own Russian text still wins.
     */
    function installPackageText(locale, overrides) {
      if (typeof locale.resolveText !== 'function') return () => {};
      const original = locale.resolveText;
      const isRussian = () => {
        const snapshot = typeof locale.getLocale === 'function' ? locale.getLocale() : locale.getSnapshot?.();
        return snapshot?.active === 'ru';
      };
      const resolve = (text) => {
        const source = typeof text === 'string' ? text : text?.en;
        const shipsRussian = typeof text === 'object' && text !== null && typeof text.ru === 'string';
        if (!shipsRussian && isRussian() && typeof source === 'string'
          && Object.prototype.hasOwnProperty.call(overrides, source)) {
          return overrides[source];
        }
        return original.call(locale, text);
      };
      try {
        locale.resolveText = resolve;
        if (locale.resolveText !== resolve) return () => {};
      } catch {
        return () => {};
      }
      return () => {
        if (locale.resolveText === resolve) locale.resolveText = original;
      };
    }

    /** Compose the Russian sentence from the structured bonus fields, or undefined to keep the server copy. */
    function bonusMessage(bonus, template) {
      const amount = bonus?.amount;
      const currency = bonus?.currency;
      const expiresAt = bonus?.expiresAt;
      if (typeof amount !== 'string' || typeof currency !== 'string' || typeof expiresAt !== 'string') return undefined;
      const when = new Date(expiresAt);
      if (Number.isNaN(when.getTime())) return undefined;
      const numeric = Number(amount);
      const money = Number.isFinite(numeric)
        ? new Intl.NumberFormat('ru-RU', { maximumFractionDigits: 2 }).format(numeric)
        : amount;
      const date = new Intl.DateTimeFormat('ru-RU', {
        day: 'numeric',
        month: 'long',
        year: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
        timeZoneName: 'short',
      }).format(when);
      return template.replace('{amount}', money).replace('{currency}', currency).replace('{date}', date);
    }

    /**
     * The Platform answers the bonus query with a pre-formatted English sentence
     * (the msg field) next to structured amount/currency/expiry, and it localizes
     * only for English and Chinese. While Russian is active, recompose that one
     * sentence from the structured fields; anything unexpected keeps the server text.
     */
    function installServerText(ctx, templates) {
      if (templates.bonusNotice === undefined) return () => {};
      const account = (typeof ctx.get === 'function' ? ctx.get('remote') : ctx.remote)?.account;
      if (account === undefined || typeof account.getUnnotifiedBonuses !== 'function') return () => {};
      const original = account.getUnnotifiedBonuses;
      const localized = async (...args) => {
        const result = await original.apply(account, args);
        const snapshot = ctx.locale?.getSnapshot?.() ?? ctx.locale?.getLocale?.();
        if (snapshot?.active !== 'ru') return result;
        const value = result?.value;
        const bonuses = Array.isArray(value) ? value : value?.bonuses;
        if (!Array.isArray(bonuses)) return result;
        const rewritten = bonuses.map((bonus) => {
          const message = bonusMessage(bonus, templates.bonusNotice);
          return message === undefined ? bonus : { ...bonus, message };
        });
        return Array.isArray(value)
          ? { ...result, value: rewritten }
          : { ...result, value: { ...value, bonuses: rewritten } };
      };
      try {
        account.getUnnotifiedBonuses = localized;
        if (account.getUnnotifiedBonuses !== localized) return () => {};
      } catch {
        return () => {};
      }
      return () => {
        if (account.getUnnotifiedBonuses === localized) account.getUnnotifiedBonuses = original;
      };
    }

    return {
      inject: ['locale'],
      apply(ctx) {
        ctx.effect(
          () => ctx.locale.addLanguage({ id: 'ru', label: 'Русский', fallback: 'en' }),
          'locale-ru: language definition',
        );
        for (const [ns, entries] of Object.entries(dictionaries)) {
          ctx.effect(() => ctx.locale.register(ns, 'ru', entries), \`locale-ru: \${ns} dictionary\`);
        }
        ctx.effect(
          () => installPackageText(ctx.locale, packageText),
          'locale-ru: package display text',
        );
        // The account service may activate after this pack; wait for it instead of blocking.
        ctx.inject(['remote'], (remoteCtx) => {
          remoteCtx.effect(
            () => installServerText(remoteCtx, serverText),
            'locale-ru: server-authored copy',
          );
        });
      },
    };
  },
});
`

fs.writeFileSync(outFile, `${banner}\n${body}`)
console.log(`wrote ${outFile}`)
console.log(`  dictionary keys: ${keyCount} across ${namespaces.length} namespaces`)
console.log(`  package display strings: ${packageTextCount}`)
console.log(`  server text templates: ${serverTextCount}`)
console.log(`  manifest text seen: ${coverage.titles} titles, ${coverage.descriptions} descriptions`)
if (uncoveredDescriptions.length) {
  console.log(`  descriptions with no Russian override: ${uncoveredDescriptions.length}`)
  for (const text of uncoveredDescriptions.slice(0, 5)) console.log(`    - ${text.slice(0, 80)}`)
}
